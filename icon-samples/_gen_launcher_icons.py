"""生成「字形 × 配色」的启动器图标矩阵，以及配套的清单别名。

# 为什么是矩阵

启动器图标是打包进 APK 的静态资源，运行时改不了像素；能改的只有「哪个组件是启动器入口」。
所以「字形」和「配色」两个自由度只能在编译期穷举成组合，再让运行时挑一个别名启用：

- **字形** 6 个：匣（原稿）+ 字形演变图里的五个古文字，各自的轮廓在 res/drawable/ic_launcher_foreground*.xml
- **配色** 73 套：7 颗固定种子（精确同色）+ 莫奈色轮 66 格（壁纸色穷举不了，就近匹配）
- 合计 **438 条 activity-alias**，各自指向一份 adaptive-icon

别名靠固定规则拼，不存对照表：
`Launcher` + 字形标签 + 配色标签，例如 `LauncherWeiboW00A`、`LauncherXiaLotus`。
AndroidManifest 与 Kotlin 两侧由本脚本和 `LauncherGlyph` 共同保证这条规则一致，
`LauncherIconManifestTest` 会读真实清单把 438 个名字全对一遍。

# 色轮取值

24 色相 × 3 彩度（28 / 40 / 52），铺在 HCT tone 40（M3 浅色 primary 的固定明度）上，
色值不是手填的，来自 LauncherWheelProbeTest 用项目实际依赖的 material-color-utilities 实测输出。
青绿色系在 tone 40 的彩度上限只有 35 上下，三档里的 40 和 52 会被 sRGB 色域压成同一个值，
去重后剩 66 格 —— 留着重复格只会让最近邻出现并列、结果不稳定。

# 产出（全部由本脚本生成，勿手改）

  1. res/values/launcher_palette.xml            —— 色轮各格底色
  2. res/mipmap-anydpi-v26/ic_launcher_*_*.xml  —— 438 份 adaptive-icon
  3. ui/theme/LauncherWheelData.kt              —— 色轮 66 格（标签 + 底色资源）
  4. AndroidManifest.xml 的 LAUNCHER_ICONS 区段 —— 438 条 activity-alias
"""
import os
import re

ROOT = r"D:/android_project/MDEditor4"
RES = os.path.join(ROOT, "app/src/main/res")
MIP = os.path.join(RES, "mipmap-anydpi-v26")
KOTLIN = os.path.join(ROOT, "app/src/main/java/com/yuzlyn/mdeditor/ui/theme/LauncherWheelData.kt")
MANIFEST = os.path.join(ROOT, "app/src/main/AndroidManifest.xml")
TABLE = os.path.join(ROOT, "app/build/launcher_wheel.txt")

TIERS = (28, 40, 52)          # 柔和 / 标准 / 鲜艳
TIER_KEY = {28: "a", 40: "b", 52: "c"}
HUE_STEP = 15

# (资源后缀, 别名标签, foreground 引用, 中文名)
GLYPHS = [
    ("xia", "Xia", "@drawable/ic_launcher_foreground", "匣"),
    ("weibo", "Weibo", "@drawable/ic_launcher_foreground_weibo", "微伯簋"),
    ("zengzhong", "Zengzhong", "@drawable/ic_launcher_foreground_zengzhong", "曾仲游父簋"),
    ("lusitu", "Lusitu", "@drawable/ic_launcher_foreground_lusitu", "魯大司徒厚氏"),
    ("shuowengu", "Shuowengu", "@drawable/ic_launcher_foreground_shuowen_gu", "說文古文"),
    ("shuowenzhu", "Shuowenzhu", "@drawable/ic_launcher_foreground_shuowen_zhu", "說文竹部"),
]

# (资源后缀, 别名标签, background 引用, 中文名)
SEEDS = [
    ("lotus", "Lotus", "@drawable/ic_launcher_bg_lotus", "蓮"),
    ("lavender", "Lavender", "@drawable/ic_launcher_bg_lavender", "薰衣草"),
    ("ocean", "Ocean", "@drawable/ic_launcher_bg_ocean", "海"),
    ("forest", "Forest", "@drawable/ic_launcher_bg_forest", "林"),
    ("clay", "Clay", "@drawable/ic_launcher_bg_clay", "陶"),
    ("rose", "Rose", "@drawable/ic_launcher_bg_rose", "玫瑰"),
    ("slate", "Slate", "@drawable/ic_launcher_bg_slate", "石"),
]


def load_cells():
    if not os.path.exists(TABLE):
        raise SystemExit(
            "缺少 %s\n先跑： ./gradlew :app:testDebugUnitTest "
            "--tests com.yuzlyn.mdeditor.LauncherWheelProbeTest" % TABLE
        )
    cells = {}
    for line in open(TABLE, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        if line.startswith("---"):
            break          # 后面是种子色那一段，不属于色轮
        hue, want, hexv, got_h, got_c, got_t = line.split("|")
        cells[(int(hue), int(want))] = hexv
    return cells


def grid(cells):
    """按色相 → 彩度展开，顺手去掉被 sRGB 色域压成同色的格。"""
    out, seen = [], set()
    for hue in range(0, 360, HUE_STEP):
        for want in TIERS:
            hexv = cells[(hue, want)]
            if hexv in seen:
                continue
            seen.add(hexv)
            out.append((hue, want, hexv))
    return out


def ident(hue, want):
    return "w%02d%s" % (hue // HUE_STEP, TIER_KEY[want])


def decl(hue, want):
    return ident(hue, want).upper()          # w00a -> W00A


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# ---------------------------------------------------------------- 1. 底色
cells = grid(load_cells())

colors = ['<?xml version="1.0" encoding="utf-8"?>',
          "<!-- GENERATED by icon-samples/_gen_launcher_icons.py · 勿手改",
          "     莫奈色轮底色：HCT tone 40，24 色相 × 3 彩度（28 柔和 / 40 标准 / 52 鲜艳）。",
          "     由 LauncherWheelProbeTest 用 material-color-utilities 实测导出；",
          "     青绿色系彩度被 sRGB 色域压到同一值的格已去重。 -->",
          "<resources>"]
for hue, want, hexv in cells:
    colors.append('    <!-- hue %3d° · 目标彩度 %d -->' % (hue, want))
    colors.append('    <color name="launcher_bg_%s">%s</color>' % (ident(hue, want), hexv))
colors.append("</resources>\n")
write(os.path.join(RES, "values", "launcher_palette.xml"), "\n".join(colors))

# ------------------------------------------------------- 2. 配色清单
# 统一成 (资源后缀, 别名标签, background 引用, 中文名)，种子在前、色轮在后。
palettes = list(SEEDS)
for hue, want, hexv in cells:
    palettes.append((ident(hue, want), decl(hue, want),
                     "@color/launcher_bg_" + ident(hue, want),
                     "%d° / 彩度 %d" % (hue, want)))

ICON_TMPL = """<?xml version="1.0" encoding="utf-8"?>
<!-- DocBox 图标 · 字形「{glabel}」× 配色 {plabel}。由 _gen_launcher_icons.py 生成，勿手改。 -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="{bg}" />
    <foreground android:drawable="{fg}" />
    <monochrome android:drawable="{fg}" />
</adaptive-icon>
"""

for gid, gtag, fg, glabel in GLYPHS:
    for pid, ptag, bg, plabel in palettes:
        write(os.path.join(MIP, "ic_launcher_%s_%s.xml" % (gid, pid)),
              ICON_TMPL.format(glabel=glabel, plabel=plabel, bg=bg, fg=fg))

# ------------------------------------------------------------ 3. Kotlin 表
kt = ['package com.yuzlyn.mdeditor.ui.theme',
      "",
      "import com.yuzlyn.mdeditor.R",
      "",
      "/**",
      " * **GENERATED by icon-samples/_gen_launcher_icons.py · 勿手改。**",
      " *",
      " * 莫奈色轮：HCT tone 40 上 24 色相 × 3 彩度（28 柔和 / 40 标准 / 52 鲜艳），去重后 66 格。",
      " * 下标即 [LauncherPalette.nearestIndex] 的返回值，别名靠 `Launcher{字形}{W00A}` 规则拼，",
      " * 与 AndroidManifest 由同一个脚本产出。",
      " */",
      "internal object LauncherWheelData {",
      "",
      "    /** 一格：别名标签（如 `W00A`）+ 底色资源。 */",
      "    class Cell(val ident: String, val colorRes: Int)",
      "",
      "    val CELLS: List<Cell> = listOf("]
for hue, want, hexv in cells:
    kt.append('        Cell("%s", R.color.launcher_bg_%s),' % (decl(hue, want), ident(hue, want)))
kt.append("    )")
kt.append("}")
write(KOTLIN, "\n".join(kt) + "\n")

# ------------------------------------------------------------ 4. manifest
alias = []
for gid, gtag, fg, glabel in GLYPHS:
    for pid, ptag, bg, plabel in palettes:
        enabled = "true" if (gid == "xia" and pid == "lotus") else "false"
        alias.append("""        <activity-alias
            android:name=".Launcher{g}{p}"
            android:targetActivity=".MainActivity"
            android:enabled="{en}"
            android:exported="true"
            android:icon="@mipmap/ic_launcher_{gi}_{pi}"
            android:roundIcon="@mipmap/ic_launcher_{gi}_{pi}"
            android:label="@string/app_name">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>""".format(g=gtag, p=ptag, en=enabled, gi=gid, pi=pid))

manifest = open(MANIFEST, encoding="utf-8").read()
new, n = re.subn(r"(<!-- LAUNCHER_ICONS_BEGIN -->)(.*?)(<!-- LAUNCHER_ICONS_END -->)",
                 lambda m: m.group(1) + "\n" + "\n".join(alias) + "\n        " + m.group(3),
                 manifest, flags=re.S)
if n != 1:
    raise SystemExit("AndroidManifest 里找不到 LAUNCHER_ICONS_BEGIN/END 标记")
write(MANIFEST, new)

# ------------------------------------------------- 5. 清掉旧命名遗留的 mipmap
keep = {"ic_launcher", "ic_launcher_round"}
keep |= {"ic_launcher_%s_%s" % (g[0], p[0]) for g in GLYPHS for p in palettes}
removed = []
for name in sorted(os.listdir(MIP)):
    stem = name[:-4] if name.endswith(".xml") else None
    if stem and stem.startswith("ic_launcher") and stem not in keep:
        os.remove(os.path.join(MIP, name))
        removed.append(name)
if removed:
    print("清理旧 mipmap %d 个（示例：%s）" % (len(removed), ", ".join(removed[:3])))

print("色轮 %d 格（原始 %d 格），配色合计 %d 套" % (len(cells), 24 * len(TIERS), len(palettes)))
print("字形 %d 个 → mipmap %d 份，别名 %d 条" % (len(GLYPHS), len(GLYPHS) * len(palettes), len(alias)))
